def _vis(s):
    """Видимая длина ячейки (без разметки формул и индексов)."""
    s = re.sub(r"\$([^$]*)\$", lambda mo: re.sub(r"\\[a-z]+|[{}^_]", "", mo.group(1)), str(s))
    return len(re.sub(r"[~^*]", "", s))


def table(header, rows, align=None):
    """Pipe-таблица; ширины столбцов задаются длиной «---» пропорционально содержимому."""
    k = len(header)
    align = align or ["---"] + [":---:"] * (k - 1)
    hw = [max(_vis(t) for t in str(h).replace("/", "/ ").split()) if str(h).strip() else 1 for h in header]
    w = [max([hw[j]] + [_vis(r[j]) for r in rows if j < len(r)]) for j in range(k)]
    w = [min(max(4, x), 40) + 2 for x in w]
    scale = max(1.0, 100 / sum(w))
    seps = []
    for a, x in zip(align, w):
        d = "-" * max(3, int(x * scale))
        seps.append((":" if a.startswith(":") else "") + d + (":" if a.endswith(":") and len(a) > 3 else ""))
    align = seps
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join(align) + "|"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines) + "\n"


