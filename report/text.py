def n(x, nd=2):
    """Число для текста и таблиц: десятичная точка, знак минус «−»."""
    s = f"{x:.{nd}f}"
    if s.startswith("-") and float(s) == 0:
        s = s[1:]
    return s.replace("-", MINUS)


def m(x, nd=3):
    """Число внутри формулы (LaTeX)."""
    s = f"{x:.{nd}f}"
    if s.startswith("-") and float(s) == 0:
        s = s[1:]
    return s


def sci(x, nd=3):
    """Экспоненциальная запись внутри формулы: 1.234 \\cdot 10^{-4}."""
    if x == 0:
        return "0"
    e = int(np.floor(np.log10(abs(x))))
    mant = x / 10 ** e
    if round(abs(mant), nd) >= 10:
        mant, e = mant / 10, e + 1
    return f"{mant:.{nd}f}" if e == 0 else f"{mant:.{nd}f} \\cdot 10^{{{e}}}"


def S(x, nd=3):
    """Экспоненциальная запись как строчная формула."""
    return f"${sci(x, nd)}$"


def frac(x, nd=5):
    """Мольная доля: обычная запись, очень малые значения — экспоненциальная."""
    if x is None or np.isnan(x):
        return "—"
    return n(x, nd) if abs(x) >= 10 ** (-nd + 1) or x == 0 else S(x, 2)


