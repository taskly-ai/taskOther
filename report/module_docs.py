def section(md: str, start: str) -> str:
    parts = re.split(r"(?m)^(?=# )", md)
    for p in parts:
        if p.startswith(start):
            return re.sub(r"```\{=openxml\}.*?```", "", p, flags=re.S).strip() + "\n"
    raise KeyError(start)


def bibliography(md: str) -> str:
    return md[md.index("# Список литературы"):].replace("# Список литературы", "## Список литературы (нумерация отчёта)")


